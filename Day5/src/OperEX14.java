
public class OperEX14 {
	
	/*
	 *  복합 대입 연산 : *=,-=,+= ....
	 */

	public static void main(String[] args) {
		
		int a =10;
		int res = 0;
		
		res +=a;
		System.out.println(res);
		
		res -=a;
		System.out.println(res);
		
		res *=a;
		System.out.println(res);
		
		res /=a;
		System.out.println(res);
		
		res >>=a;
		System.out.println(res);
		
		res <<=a;
		System.out.println(res);
		
		res ^=a;
		System.out.println(res);
		

	}

}
