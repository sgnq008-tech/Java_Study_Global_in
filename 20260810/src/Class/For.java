public class For { // 이름을 넣어줄떄는 키워드랑 같은 변수명같은 거는 에러가 날 수 있으니 피해주기

	public static void main(String[] args) {
		int s;
		
		for(s= 1; s < 101; s++) {
			System.out.print(s+" ");
		}
		

	}

}
