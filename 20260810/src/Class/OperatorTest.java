package Class;

public class OperatorTest {
    public static void main(String[] args) {
        int a = 10;
        int b = 3;

        // 1. 몫 구하기 (나누기 연산자 사용)
        int quotient = a / b;

        // 2. 나머지 구하기 (나머지 연산자 % 사용)
        int remainder = a % b; // 여기를 채워보세요!

        // 3. 결과 출력
        System.out.println("몫: " + quotient);
        System.out.println("나머지: " + remainder);
    }
}