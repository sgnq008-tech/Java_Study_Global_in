package Level1Practice;

// ==========================================
// 1. 부모 클래스 (AnimalEx)
// 모든 동물 객체들이 공통으로 가질 속성(변수)과 동작(메서드)을 정의하는 상위 틀
// ==========================================
class Animal {
    String name = "동물"; // 모든 동물 객체가 공통으로 물려받는 멤버 변수

    // 모든 동물 객체가 공통으로 물려받아 사용할 수 있는 메서드
    void eat() {
        System.out.println("음식을 먹습니다.");
    }
}

// ==========================================
// 2. 자식 클래스 (DogEx)
// extends AnimalEx: AnimalEx(부모)의 모든 필드와 메서드를 그대로 상속받음
// ==========================================
class Dog extends Animal {
    // DogEx 전용 확장 메서드 (부모 클래스에는 없는 강아지만의 고유 동작 추가)
    void bark() {
        System.out.println("멍멍! 짖습니다.");
    }
}

// ==========================================
// 3. 자식 클래스 (CatEx)
// extends AnimalEx: 마찬가지로 부모(AnimalEx)의 기능을 동일하게 상속받음
// ==========================================
class Cat extends Animal {
    // CatEx 전용 확장 메서드 (고양이만의 고유 동작 추가)
    void meow() {
        System.out.println("야옹~ 소리를 냅니다.");
    }
}

// ==========================================
// 4. 실행 메인 클래스 (파일명: Level1Practice.java)
// 자바 프로그램의 시작점(main 메서드)을 포함하는 메인 클래스
// ==========================================
public class Animals {
    public static void main(String[] args) {
        
        System.out.println("=== 1. 강아지 객체 생성 ===");
        // [코드 의미] DogEx 클래스를 기반으로 메모리에 실제 인스턴스(객체)를 생성
        Dog dog = new Dog();
        
        // [코드 의미] DogEx 클래스 내부에는 eat()이 직접 작성되어 있지 않지만,
        //             부모(AnimalEx)로부터 상속받았기 때문에 에러 없이 호출됨
        // [출력 결과] 음식을 먹습니다.
        dog.eat();

        // [코드 의미] 자식 클래스(DogEx)에서 자체 정의한 고유 메서드 호출
        // [출력 결과] 멍멍! 짖습니다.
        dog.bark();


        System.out.println("\n=== 2. 고양이 객체 생성 ===");
        // [코드 의미] CatEx 클래스를 기반으로 고양이 인스턴스(객체) 생성
        Cat cat = new Cat();
        
        // [코드 의미] CatEx 역시 부모(AnimalEx)의 자식이므로 상속받은 eat() 재사용
        // [출력 결과] 음식을 먹습니다.
        cat.eat();

        // [코드 의미] 자식 클래스(CatEx)에서 자체 정의한 고유 메서드 호출
        // [출력 결과] 야옹~ 소리를 냅니다.
        cat.meow();
    }
}