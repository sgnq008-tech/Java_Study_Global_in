package practice;

public class ex2 {

	public static void main(String[] args) {
		/*
		 * int a = 10;
		 * 
		 * a += 2;
		 * 
		 * System.out.println(a);
		 * 
		 * a %= 5;
		 * 
		 * System.out.println(a);
		 */
		
		int a = 10, b = 10;
		
		System.out.println(++a);
		// a에 1를 더한 값 
		System.out.println(b++);
		// b에 1를 더한 값 

        System.out.println(--a);
       // a에 1를 뺀 값  

		System.out.println(b--);
		// b에 1를 뺀 값 

	
		
		
	}

}
