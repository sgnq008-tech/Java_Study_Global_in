package practice;

public class ex3 {
    
	public static void main(String[] args) {
		
		int a = 10, b = 5;
		
		System.out.println((a==10) || (b==5));
		// a는10 또는 b가 5면 true, 나머지는 false
		System.out.println((a==10) && (b==5));
        // a는10 그리고 b가 5면 true, 나머지는 false
		System.out.println(!(a==10));
        // 부정형으로 a는 10아니면 false, 다른 거면 전부 true
		

	
	}
}
